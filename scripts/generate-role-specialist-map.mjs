#!/usr/bin/env node
// Generates the role-to-specialist map from config/specialists/*.specialist.json.
//
// Canonical output (committed): config/catalog/role-specialist-map.json
// Runtime copies for the Claude plugin (marketplace installs copy only the plugin
// folder, so neither consumer can reach config/ at runtime):
// - plugins/specialists/scripts/role-specialist-map.generated.json (byte-identical
//   JSON, read by scripts/session-start.mjs)
// - plugins/specialists/hooks/role-specialist-map.generated.ts (same map as a TS
//   module, imported by hooks/register.tsx — the Mod loader only loads code files,
//   never JSON)
//
// The CANDIDATES table below is the only hand-kept part: generic task roles to
// candidate specialist names. Every candidate is validated against the catalog —
// a name without config/specialists/<name>.specialist.json (or a template entry
// such as bare) is dropped, never shipped. Run with --check to verify the
// committed files match a fresh generation (used by the drift test).
//
// Usage: node scripts/generate-role-specialist-map.mjs [--check]

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const CANONICAL = join(ROOT, 'config', 'catalog', 'role-specialist-map.json');
const RUNTIME_JSON = join(ROOT, 'plugins', 'specialists', 'scripts', 'role-specialist-map.generated.json');
const RUNTIME_TS = join(ROOT, 'plugins', 'specialists', 'hooks', 'role-specialist-map.generated.ts');

// Generic task role -> candidate specialist names. Candidates MUST name real
// dispatchable specialists; anything without a definition file is dropped below
// (so deploy-watcher, production-monitor can never appear here).
const CANDIDATES = [
  ['review', ['reviewer', 'seconder', 'pr-reviewer']],
  ['quant', ['quant-methodologist', 'quant-researcher']],
  ['deep-analysis', ['overthinker']],
  ['deploy', ['test-runner', 'reviewer']],
  ['monitor', ['test-runner', 'debugger']],
  ['implement', ['executor']],
  ['explore', ['explorer', 'researcher']],
  ['plan', ['planner']],
  ['test', ['test-engineer', 'test-runner']],
  ['security', ['security-auditor']],
  ['debug', ['debugger']],
  ['coordinate', ['chain-coordinator', 'node-coordinator']],
  ['docs', ['sync-docs', 'service-knowledge-sync']],
  ['changelog', ['changelog-keeper', 'changelog-drafter']],
  ['merge', ['xt-merge']],
  ['transcribe', ['transcriber']],
  ['obligations', ['obligations-scanner']],
  ['author', ['specialists-creator']],
];

function definitionExists(name) {
  const path = join(ROOT, 'config', 'specialists', `${name}.specialist.json`);
  if (!existsSync(path)) return false;
  try {
    const parsed = JSON.parse(readFileSync(path, 'utf8'));
    // Templates (bare) are not dispatchable roles.
    return parsed?.specialist?.metadata?.category !== 'template';
  } catch {
    return false;
  }
}

function generate() {
  const roles = {};
  for (const [role, names] of CANDIDATES) {
    const kept = names.filter((name) => {
      const ok = definitionExists(name);
      if (!ok) process.stderr.write(`[role-map] dropping ${role} -> ${name}: no dispatchable definition file\n`);
      return ok;
    });
    if (kept.length === 0) {
      process.stderr.write(`[role-map] dropping role ${role}: no surviving specialist\n`);
      continue;
    }
    roles[role] = kept;
  }
  return {
    _generated_by: 'scripts/generate-role-specialist-map.mjs',
    _source: 'config/specialists/*.specialist.json',
    roles,
  };
}

const map = generate();
const jsonText = `${JSON.stringify(map, null, 2)}\n`;
const tsText = `// GENERATED by scripts/generate-role-specialist-map.mjs — do not edit.\n` +
  `// Canonical source: config/catalog/role-specialist-map.json\n` +
  `export const ROLE_SPECIALIST_MAP: Record<string, string[]> = ${JSON.stringify(map.roles)};\n`;

if (process.argv.includes('--check')) {
  let ok = true;
  for (const [path, expected] of [[CANONICAL, jsonText], [RUNTIME_JSON, jsonText], [RUNTIME_TS, tsText]]) {
    let current = null;
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      /* missing file is drift */
    }
    if (current !== expected) {
      process.stderr.write(`[role-map] drift: ${path} does not match fresh generation\n`);
      ok = false;
    }
  }
  process.exit(ok ? 0 : 1);
}

writeFileSync(CANONICAL, jsonText, 'utf8');
writeFileSync(RUNTIME_JSON, jsonText, 'utf8');
writeFileSync(RUNTIME_TS, tsText, 'utf8');
console.log(`[role-map] wrote ${CANONICAL}, ${RUNTIME_JSON} and ${RUNTIME_TS}`);
